def comprobar() -> None:
    """Falla ruidosamente si algun glifo no es 7x5. Lo llama el generador."""
    for clave, filas in BASE.items():
        if len(filas) != 7:
            raise ValueError("%r tiene %d filas, deberian ser 7" % (clave, len(filas)))
        for i, fila in enumerate(filas):
            if len(fila) != 5:
                raise ValueError("%r fila %d mide %d, deberia medir 5" % (clave, i, len(fila)))
